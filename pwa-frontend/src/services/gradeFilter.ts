/** 学年ごとの最大難易度（学科共通） */
const GRADE_MAX_DIFFICULTY: Record<number, number> = {
  1: 3, // 基礎的な問題のみ
  2: 4, // 応用問題含む
  3: 5, // 本番レベル
};

/**
 * 指定学科・学年で出題可能なカテゴリ一覧を返す
 */
export function getCategoriesForGrade(grade: number, department?: Department): string[] {
  const dept = department || 'nursing';
  const deptCategories = GRADE_CATEGORIES[dept];
  if (!deptCategories) return GRADE_CATEGORIES.nursing[3]!;
  return deptCategories[grade] || deptCategories[3]!;
}

/**
 * 指定学年の最大難易度を返す
 */
export function getMaxDifficultyForGrade(grade: number): number {
  return GRADE_MAX_DIFFICULTY[grade] || 5;
}

/**
 * 指定カテゴリが学年の出題範囲内かチェック
 */
export function isCategoryAvailableForGrade(category: string, grade: number, department?: Department): boolean {
  const categories = getCategoriesForGrade(grade, department);
  return categories.includes(category);
}
